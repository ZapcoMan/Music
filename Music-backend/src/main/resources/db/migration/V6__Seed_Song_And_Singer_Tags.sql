-- ---------- 回填逗号串，使 song.tags / singer.tags 与中间表一致 ----------
-- 此前两侧双轨无同步（工程债#19 的数据面）。以 song_tag/singer_tag 为真源，
-- 只回填当前为空的行，不覆盖已有内容。
UPDATE `song` s
SET s.tags = (
    SELECT GROUP_CONCAT(t.name ORDER BY t.id SEPARATOR ',')
    FROM song_tag st JOIN tag t ON t.id = st.tag_id
    WHERE st.song_id = s.id
)
WHERE s.tags IS NULL OR s.tags = '';

UPDATE `singer` g
SET g.tags = (
    SELECT GROUP_CONCAT(t.name ORDER BY t.id SEPARATOR ',')
    FROM singer_tag gt JOIN tag t ON t.id = gt.tag_id
    WHERE gt.singer_id = g.id
)
WHERE g.tags IS NULL OR g.tags = '';
